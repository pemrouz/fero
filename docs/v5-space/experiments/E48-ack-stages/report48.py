#!/usr/bin/env python3
"""report48.py: results/summary.md from results/runs.json (every run of run48.py).

One section per (rule set, rules dropped, mode); one row per config (form and
stage map, `-blind` when early answers carry no result), one column per bound.
A cell is `ok` (every reachable state explored, nothing broken, every program
can end), the properties broken with the length of the shortest trace, or
`LIMIT` (stopped at the state limit with no counterexample: a partial check).
A run that stops at its first break shows that break only.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DB = json.load(open(os.path.join(HERE, 'results', 'runs.json')))
BASEB = ['txn', 'txnb', 'txn1', 'dedup', 'lockAA', 'lockBA', 'lockAB', 'pipe', 'pipe-t', 'ryw', 'pipe-s']
ORDER = BASEB + [b + '-c' for b in BASEB] + ['txn1-2r', 'dedup-v', 'lockAA-v', 'lockAB-v', 'pipe3']
CFGS = ['S0', 'S1-recv', 'S1-repl', 'S1-mixr', 'S1-mixp', 'S1-recv-blind', 'S1-repl-blind', 'S1-mixr-blind',
        'S1-mixp-blind', 'S2-mem', 'S2-disk', 'S2-e1']


def cell(x):
    if x['fail']:
        return ', '.join(f'{p} {x["fail"][p][0]}' for p in sorted(x['fail']))
    if not x['complete']:
        return 'LIMIT'
    live = x.get('judged', {}).get('done')
    if live and live[1]:
        return f'stuck {live[1]}'
    return 'ok'


rows = {}
models = set()
total = [0, 0.0, 0]
for k, x in DB.items():
    model, form, stage, res, rules, bound, _settings, mode, drop, allfails, limit = json.loads(k)
    models.add(model)
    total[0] += 1
    total[1] += x['secs']
    total[2] += x['states']
    c = form + ('' if form == 'S0' else '-' + stage) + ('-blind' if res == 'blind' else '')
    rk = ('+'.join(rules) or 'none', ', '.join(drop), mode + (', every property' if allfails else ''))
    rows.setdefault(rk, {})[(c, bound)] = x

print('# E-48 summary (generated by report48.py from results/runs.json)')
print()
print(f'Model: models/ackstage.py, sha256 prefix {", ".join(sorted(models))} (every run below used it). '
      f'{total[0]:,} runs, {total[2]:,} states, {total[1]:,.0f} s of CPU in all.')
print()
print('Cells: `ok` = every reachable state explored, nothing broken, and every program can end; '
      '`P n` = property P broken, shortest trace n steps; `LIMIT` = stopped at the state limit with no '
      'counterexample (partial); `stuck n` = n states from which the programs cannot all end. A bound ending '
      'in `-c` has the leader\'s process crash in place of a power loss. Configs: S0 persisted only; S1-<map> '
      'ack stages with commit at disk; S2-<map> commit in memory; `-blind` = early answers carry no result. '
      'In `info` rows the properties are what an early answer\'s contract allows.')
for (rules, drop, mode) in sorted(rows, key=lambda r: (r[2].startswith('info'), r[0] != 'none', r[0], r[1], r[2])):
    cols = rows[(rules, drop, mode)]
    bounds = [b for b in ORDER if any(bb == b for _, bb in cols)]
    cfgs = sorted({c for c, _ in cols}, key=lambda c: CFGS.index(c) if c in CFGS else 99)
    title = f'rules {rules}' + (f', dropped {drop}' if drop else '') + (f' ({mode} mode)' if mode != 'bug' else '')
    states = sum(x['states'] for x in cols.values())
    secs = sum(x['secs'] for x in cols.values())
    print()
    print(f'## {title} ({len(cols)} runs, {states:,} states, {secs:,.0f} s)')
    print()
    print('| config | ' + ' | '.join(bounds) + ' |')
    print('|---|' + '---|' * len(bounds))
    for c in cfgs:
        print(f'| {c} | ' + ' | '.join(cell(cols[(c, b)]) if (c, b) in cols else '' for b in bounds) + ' |')
