#!/usr/bin/env python3
"""E-03: fold the raw JSON lines of the 3 timing runs into tables (results/tables.md).
For each measure: the median over runs of each run's median, and the spread (min..max of the run medians).
python3 -I summarize.py"""
import json, os, statistics, collections

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, 'results')

def load(name):
    p = os.path.join(R, name)
    if not os.path.exists(p):
        return [], []
    runs, rows, cur = [], [], None
    for line in open(p):
        line = line.strip()
        if not line.startswith('{'):
            continue
        o = json.loads(line)
        if 'loadavg' in o:
            cur = o['run']; runs.append(o); continue
        o['_run'] = cur
        rows.append(o)
    return runs, rows

def fold(rows, key, fields=('ns',)):
    g = collections.OrderedDict()
    for o in rows:
        g.setdefault(key(o), []).append(o)
    out = []
    for k, os_ in g.items():
        d = {'key': k, 'runs': len(os_)}
        for f in fields:
            xs = [o[f] for o in os_ if f in o]
            if xs:
                d[f] = statistics.median(xs); d[f + '_lo'] = min(xs); d[f + '_hi'] = max(xs)
        out.append(d)
    return out

def fmt(x):
    if x is None: return ''
    if abs(x) >= 100: return f'{x:,.0f}'
    if abs(x) >= 10: return f'{x:.1f}'
    return f'{x:.2f}'

def table(title, rows, fields, heads):
    s = [f'### {title}', '', '| measure | ' + ' | '.join(heads) + ' | runs |', '|---|' + '---|' * len(heads) + '---|']
    for d in rows:
        cells = []
        for f in fields:
            if f in d:
                lo, hi = d.get(f + '_lo'), d.get(f + '_hi')
                cells.append(f'{fmt(d[f])} ({fmt(lo)}-{fmt(hi)})' if lo is not None and lo != hi else fmt(d[f]))
            else:
                cells.append('')
        s.append(f"| {d['key']} | " + ' | '.join(cells) + f" | {d['runs']} |")
    return '\n'.join(s) + '\n'

parts = ['# E-03 tables (generated by summarize.py from results/*.jsonl)', '',
         'Each cell: the median over the timing runs of each run\'s median, then (min-max of the run medians).', '']
for name, title in [('napi.jsonl', 'napi seam, Node 22'), ('napi-node26.jsonl', 'napi seam, Node 26')]:
    runs, rows = load(name)
    if rows:
        parts.append(f"load averages at start: {', '.join(r['loadavg'].split()[0] for r in runs)}\n")
        parts.append(table(title + ' (ns per call or per record)', fold(rows, lambda o: o['measure'], ('ns', 'processCpuNsPerRec')), ('ns', 'processCpuNsPerRec'), ('ns (wall)', 'process CPU ns/record')))
runs, rows = load('fold.jsonl')
if rows:
    parts.append(f"load averages at start: {', '.join(r['loadavg'].split()[0] for r in runs)}\n")
    parts.append(table('X3: a batch of 256 records into data\'s fold, Node 22 (ns per record)', fold(rows, lambda o: o['measure']), ('ns',), ('ns/record',)))
runs, rows = load('isolate.jsonl')
if rows:
    parts.append(f"load averages at start: {', '.join(r['loadavg'].split()[0] for r in runs)}\n")
    perf = [o for o in rows if o['measure'] != 'memory']
    parts.append(table('EMB-V8: the same JS in four hosts (ns per op, per loop step, or per record)', fold(perf, lambda o: o['host'] + ' | ' + o['measure']), ('ns',), ('ns',)))
    mem = [o for o in rows if o['measure'] == 'memory']
    s = ['### Memory (one sample per run; median shown)', '', '| host | create (µs) | load data bundle (ms) | bare heap (bytes) | heap for data\'s code (bytes) | heap per row (bytes) | RSS after (MB) |', '|---|---|---|---|---|---|---|']
    g = collections.OrderedDict()
    for o in mem: g.setdefault(o['host'], []).append(o)
    med = lambda xs: statistics.median(xs) if xs else None
    for h, os_ in g.items():
        s.append(f"| {h} | {fmt(med([o.get('createUs') for o in os_ if 'createUs' in o]))} | {fmt(med([o['loadMs'] for o in os_]))} | {fmt(med([o.get('heapBareBytes') for o in os_ if 'heapBareBytes' in o]))} | {fmt(med([o['heapDataLoadedBytes'] for o in os_]))} | {fmt(med([o['heapPerRowBytes'] for o in os_]))} | {fmt(med([o['rssBytes'] / 1e6 for o in os_]))} |")
    parts.append('\n'.join(s) + '\n')
runs, rows = load('seam.jsonl')
if rows:
    parts.append(f"load averages at start: {', '.join(r['loadavg'].split()[0] for r in runs)}\n")
    parts.append(table('SIDE: a Rust daemon to a Node process (ns per 100 B record)', fold(rows, lambda o: o['measure'], ('ns', 'nodeCpuNsPerRec', 'daemonCpuNsPerRec', 'rttUs')), ('ns', 'nodeCpuNsPerRec', 'daemonCpuNsPerRec', 'rttUs'), ('ns (wall)', 'Node CPU ns', 'daemon CPU ns', 'round trip µs')))
open(os.path.join(R, 'tables.md'), 'w').write('\n'.join(parts))
print('\n'.join(parts))
