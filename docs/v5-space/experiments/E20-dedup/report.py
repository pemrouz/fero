#!/usr/bin/env python3
"""report.py: E-20's summary from the ablation files.

    python3 report.py results/*-ablation.json > results/summary.md

First a table across options (rules needed by DEV-10, by role; what Y `fwd`
adds over Y `smart`; mutants), then each option in full with E-16's
report.one (the same layout as E-16 and E-33).
"""
import importlib.util
import json
import os
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location('e16report', os.path.join(HERE, '..', 'E16-controller-loop', 'engine', 'report.py'))
e16 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(e16)

ORDER = ['win-smart', 'win-fwd', 'sess-smart', 'sess-fwd', 'pid-smart', 'pid-fwd', 'keys-smart', 'keys-fwd',
         'win-fwd-all', 'sess-fwd-all']


def load(paths):
    out = {}
    for p in paths:
        o = json.load(open(p))
        name = o.get('option') or os.path.basename(p).replace('-ablation.json', '')
        tag = os.path.basename(p).replace('-ablation.json', '')
        out[tag] = o
    return out


def kept(o):
    return [r for r in o.get('rules', []) if r['kept'] and not r.get('pinned')]


def mut(o):
    ms = o.get('mutants', [])
    c = sum(1 for m in ms if m['caught'])
    eq = sum(1 for m in ms if not m['caught'] and m.get('equivalent'))
    und = sum(1 for m in ms if m.get('undecided'))
    return c, len(ms) - eq, eq, und, len(ms) - c - eq - und


def main():
    res = load(sys.argv[1:])
    tags = [t for t in ORDER if t in res] + sorted(t for t in res if t not in ORDER)
    print('# E-20 ablation summary\n')
    print('Generated by `report.py` from `results/*-ablation.json` (DEV-10 on E-16\'s engine). A rule is one guard '
          'conjunct or one update; it is counted when removing it lets the checker find a counterexample on some '
          'bound. Pinned rules (world bookkeeping, each design\'s memory bounds and its answers at once) are not '
          'counted.\n')
    print('| option | rules needed | by role | mutants caught / non-equivalent | survived | states per bound (design) |')
    print('|---|---|---|---|---|---|')
    for t in tags:
        o = res[t]
        k = kept(o)
        roles = Counter(r['role'] for r in k)
        c, ne, eq, und, sv = mut(o)
        states = '; '.join(f'{b} {x["states"]:,}' for b, x in o.get('base', {}).items())
        vr = o.get('verify_result') or {}
        states += ''.join(f'; {b} {x["states"]:,} (verify)' for b, x in vr.items())
        err = f' **error: {o["error"]}**' if o.get('error') else ''
        print(f'| {t} | **{len(k)}**{err} | ' + ', '.join(f'{a} {n}' for a, n in sorted(roles.items())) +
              f' | {c} / {ne} | {sv} | {states} |')
    print()
    for d in ('win', 'sess', 'pid', 'keys'):
        a, b = res.get(f'{d}-smart'), res.get(f'{d}-fwd')
        if not a or not b:
            continue
        ka = {r['id'] for r in kept(a)}
        kb = {r['id'] for r in kept(b)}
        print(f'- **{d}**: `fwd` keeps {len(kb)}, `smart` {len(ka)}. Only in `fwd`: ' +
              (', '.join(f'`{x}`' for x in sorted(kb - ka)) or 'none') + '. Only in `smart`: ' +
              (', '.join(f'`{x}`' for x in sorted(ka - kb)) or 'none') + '.')
    print()
    for t in tags:
        o = res[t]
        o['option'] = t
        tmp = os.path.join(HERE, 'results', f'.tmp-{os.getpid()}-{t}.json')
        with open(tmp, 'w') as f:
            json.dump(o, f)
        e16.one(tmp)
        os.remove(tmp)


if __name__ == '__main__':
    main()
