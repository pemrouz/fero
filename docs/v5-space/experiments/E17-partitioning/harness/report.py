#!/usr/bin/env python3
"""
report.py: turn results/<option>-ablation.json into results/summary.md.

    python3 harness/report.py > results/summary.md
"""

import io
import json
import os
import sys
import tokenize

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RES = os.path.join(ROOT, 'results')
ORDER = ('fixN', 'rekey', 'rekey-alt', 'rekey-rev', 'rekey+giveup', 'rekey+giveup-alt', 'rekey-carry', 'rekey-carry-alt',
         'rekey-carry-rev', 'rekey-carry+giveup', 'slot', 'slot-rev', 'slot+giveup', 'slot+abort',
         'pslot', 'pslot-rev', 'pslot+giveup', 'split', 'split-rev', 'split+giveup',
         'lanes', 'lanes-rev', 'lanes+giveup')


def code_lines(path):
    """Lines that hold code: no blank lines, comments or docstrings."""
    src = open(path).read()
    lines = set()
    prev = None
    for tok in tokenize.generate_tokens(io.StringIO(src).readline):
        if tok.type == tokenize.STRING and prev in (tokenize.INDENT, tokenize.NEWLINE, tokenize.DEDENT, None):
            prev = tok.type
            continue
        if tok.type not in (tokenize.COMMENT, tokenize.NL, tokenize.NEWLINE, tokenize.INDENT,
                            tokenize.DEDENT, tokenize.ENDMARKER):
            for ln in range(tok.start[0], tok.end[0] + 1):
                lines.add(ln)
        prev = tok.type
    return len(lines)


def ff(x):
    if not x:
        return '-'
    b, p, d, allp = x
    return f'{p} on {b} ({d} steps)'


def main():
    sys.path.insert(0, HERE)
    import runner
    from world import PROPS
    out = []
    w = out.append
    w('# E-17 part 1: results\n')
    w('Generated by `harness/report.py` from `results/<option>-ablation.json`. An option '
      'name with `+giveup` is the same model with its give-up path pinned (never dropped). '
      '`LIMIT` means the run stopped at 1.5 million states with no counterexample: undecided. '
      'An undecided rule is kept and marked `undecided`; an undecided mutant is never counted as caught. '
      'Kept = pinned + undecided + necessary (removing it breaks a property). '
      'Properties: ' + '; '.join(f'**{k}** {v}' for k, v in PROPS.items()) + '.\n')
    names = [n for n in ORDER if os.path.exists(os.path.join(RES, f'{n}-ablation.json'))]
    data = {n: json.load(open(os.path.join(RES, f'{n}-ablation.json'))) for n in names}
    w('## Per option\n')
    w('| Option | Rules as designed | Kept (smallest set) | of which pinned / undecided | of which guards / updates | '
      'Model lines | States at the smallest model, per bound | Seconds (sum) | '
      'Mutants: caught / equivalent / undecided / survived |')
    w('|---|---|---|---|---|---|---|---|---|')
    for n in names:
        d = data[n]
        if 'error' in d:
            w(f'| {n} | error: {d["error"]} | | | | | | |')
            continue
        rows = d['rules']
        kept = [r for r in rows if r['kept']]
        g = sum(1 for r in kept if r['kind'] == 'guard')
        u = len(kept) - g
        pin = sum(1 for r in kept if r.get('pinned'))
        und = sum(1 for r in kept if not r.get('pinned') and r.get('final') and r['final'][1] == 'LIMIT')
        _, path = runner.load(n.split('+')[0].replace('-alt', '').replace('-rev', ''))
        mini = d['minimal']
        mini.update(d.get('verify', {}))
        st = ', '.join(f'{b} {mini[b]["states"]:,}' for b in mini)
        secs = sum(mini[b]['secs'] for b in mini)
        m = d.get('mutants', [])
        c = sum(1 for x in m if x['caught'] and x['caught'][1] != 'LIMIT')
        e = sum(1 for x in m if not x['caught'] and x.get('equivalent'))
        mu = sum(1 for x in m if x.get('undecided') or (x['caught'] and x['caught'][1] == 'LIMIT'))
        mt = f'{c} / {e} / {mu} / {len(m) - c - e - mu}' if m else 'not run'
        vu = ' (verify undecided: ' + ff(d['verify_undecided']) + ')' if d.get('verify_undecided') else ''
        w(f'| {n} | {len(rows)} | **{len(kept)}** | {pin} / {und} | {g} / {u} | {code_lines(path)} | {st}{vu} | '
          f'{secs:.0f} | {mt} |')
    w('')
    for n in names:
        d = data[n]
        if 'error' in d:
            continue
        w(f'## {n}\n')
        base = d['base']
        w('As designed: ' + ', '.join(f'{b} {base[b]["states"]:,} states ({base[b]["secs"]}s)' for b in base) + '.\n')
        w('| Rule | Role | Kept | Without it, alone | Without it, in the smallest model |')
        w('|---|---|---|---|---|')
        for r in d['rules']:
            k = ('pinned' if r.get('pinned') else
                 'undecided' if r.get('final') and r['final'][1] == 'LIMIT' else 'yes') if r['kept'] else 'no'
            w(f'| `{r["id"]}`{" [" + r["cmp"] + "]" if r.get("cmp") else ""} | {r["role"]} | {k} | '
              f'{ff(r["alone"])} | {ff(r.get("final"))} |')
        w('')
        if d.get('greedy'):
            w('Greedy order: ' + '; '.join(f'`{a}` {b}' for a, b in d['greedy']) + '.\n')
        m = d.get('mutants', [])
        if m:
            w('| Mutant | Kind | Caught by |')
            w('|---|---|---|')
            for x in m:
                if x.get('undecided') or (x['caught'] and x['caught'][1] == 'LIMIT'):
                    cb = 'undecided: ' + ff(x.get('undecided') or x['caught'])
                elif x['caught']:
                    cb = ff(x['caught'])
                elif x.get('equivalent'):
                    cb = 'not caught: equivalent (the same state graph on every bound)'
                else:
                    cb = 'NOT CAUGHT (survived)'
                w(f'| `{x["rule"]}` | {x["kind"]} | {cb} |')
            w('')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
