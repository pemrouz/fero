#!/usr/bin/env python3
"""
compare.py: this re-run's ablations against the originals of E-17 parts 1
and 2, field by field. Prints markdown (results/compare.md).

    python3 compare.py --work $SP/e17c/work

For each result name it compares: the rules as written, the rules kept and
the set removed (as sets, and the greedy order), each rule's pass-1 verdict
("necessary alone": the bound, property and steps of the first failure),
each kept rule's final-pass verdict, the state count and digest of the model
as written and of the smallest model on every bound, the verify bound, the
warm start, and every mutant (kind, rule, caught or equivalent or survived,
and where it was caught). The digest is (states, edges, a hash of the state
set) under PYTHONHASHSEED=0, so equal digests mean equal state sets.
"""

import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ORIG = os.path.join(os.path.dirname(HERE), 'E17-partitioning', 'results')

NAMES = ('fixN', 'slot', 'rekey', 'rekey-carry', 'lanes', 'lanes-carry', 'pslot', 'split', 'pslot-fused',
         'slot-rev', 'rekey-alt', 'rekey-carry-alt', 'rekey-rev', 'rekey-carry-rev', 'lanes-rev', 'pslot-rev',
         'split-rev', 'pslot-fused-rev',
         'slot+giveup', 'slot+abort', 'rekey+giveup', 'rekey+giveup-alt', 'rekey-carry+giveup',
         'pslot+abort', 'lanes+abort', 'split+giveup', 'pslot-fused+abort')


def load(path):
    try:
        with open(path) as f:
            return json.load(f)
    except FileNotFoundError:
        return None


def mut_counts(rows):
    if rows is None:
        return None
    c = sum(1 for r in rows if r.get('caught'))
    e = sum(1 for r in rows if not r.get('caught') and r.get('equivalent'))
    u = sum(1 for r in rows if r.get('undecided'))
    return (len(rows), c, e, len(rows) - c - e - u, u)


def verdict(x):
    """A first failure without its full property list: (bound, prop, steps)."""
    return None if not x else tuple(x[:3])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--work', required=True)
    a = ap.parse_args()
    mine_dir = os.path.join(a.work, 'results')
    out = []
    w = out.append
    w('# E-17 part 3: the re-run against the originals\n')
    w('Generated by `compare.py`. "orig" is `../E17-partitioning/results/<name>-ablation.json` '
      '(parts 1 and 2); "re-run" is this re-run, from scratch, on a byte-identical copy of the harness and '
      'models (`results/sources.sha256`), with fresh checkpoints. Mutants are (made, caught, equivalent, '
      'survived, undecided). States are the model as written, then the smallest model, on '
      'grow, shrink, both, read, deep, twice; "digests" says whether every state set is identical.\n')
    w('| Result | Rules | Kept orig / re-run | Same set removed | Same greedy order | Pass 1 same | '
      'Final pass same | Mutants orig / re-run | Mutant rows same | States as written same | '
      'Smallest-model states (re-run) | Smallest digests same | Verify (twice1) |')
    w('|---|---|---|---|---|---|---|---|---|---|---|---|---|')
    notes = []
    for n in NAMES:
        o = load(os.path.join(ORIG, f'{n}-ablation.json'))
        m = load(os.path.join(mine_dir, f'{n}-ablation.json'))
        if o is None or m is None:
            w(f'| {n} | {"no original" if o is None else ""}{"not re-run yet" if m is None else ""} |'
              + ' |' * 11)
            continue
        if 'error' in m or 'error' in o:
            w(f'| {n} | error: orig {o.get("error")}; re-run {m.get("error")} |' + ' |' * 11)
            continue
        ro = {r['id']: r for r in o['rules']}
        rm = {r['id']: r for r in m['rules']}
        kept_o = sum(r['kept'] for r in o['rules'])
        kept_m = sum(r['kept'] for r in m['rules'])
        same_set = set(o['removed']) == set(m['removed'])
        same_order = o['removed'] == m['removed']
        p1 = all(verdict(ro[i]['alone']) == verdict(rm[i]['alone']) for i in ro) and set(ro) == set(rm)
        fin = all(verdict(ro[i].get('final')) == verdict(rm[i].get('final')) for i in ro if ro[i]['kept'])
        mo, mm = mut_counts(o.get('mutants')), mut_counts(m.get('mutants'))
        if o.get('mutants') is not None and m.get('mutants') is not None:
            ko = [(r['kind'], r['rule'], bool(r.get('caught')), r.get('equivalent'), verdict(r.get('caught')))
                  for r in o['mutants']]
            km = [(r['kind'], r['rule'], bool(r.get('caught')), r.get('equivalent'), verdict(r.get('caught')))
                  for r in m['mutants']]
            mrows = 'yes' if ko == km else 'NO'
            if ko != km:
                for x, y in zip(ko, km):
                    if x != y:
                        notes.append(f'{n}: mutant differs: orig {x}, re-run {y}')
        else:
            mrows = '-'
        bs = m['bounds']
        sw = all(o['base'][b]['digest'] == m['base'][b]['digest'] for b in bs)
        smin = ', '.join(f'{m["minimal"][b]["states"]:,}' for b in bs)
        dmin = all(o['minimal'][b]['digest'] == m['minimal'][b]['digest'] for b in bs)
        vo, vm = o.get('verify', {}).get('twice1'), m.get('verify', {}).get('twice1')
        if vm:
            vtxt = f'{vm["states"]:,} {"holds" if not vm["fail"] and vm["complete"] else "LIMIT" if not vm["complete"] else "FAILS"}'
            if vo and vo['digest'] != vm['digest']:
                vtxt += ' (digest differs)'
        else:
            vtxt = '-'
        yn = lambda x: 'yes' if x else 'NO'   # noqa: E731
        w(f'| {n} | {len(rm)} | {kept_o} / {kept_m} | {yn(same_set)} | {yn(same_order)} | {yn(p1)} | {yn(fin)} | '
          f'{mo} / {mm} | {mrows} | {yn(sw)} | {smin} | {yn(dmin)} | {vtxt} |')
        if not same_set:
            notes.append(f'{n}: removed only in orig: {sorted(set(o["removed"]) - set(m["removed"]))}; '
                         f'only in re-run: {sorted(set(m["removed"]) - set(o["removed"]))}')
        if not p1:
            for i in ro:
                if verdict(ro[i]['alone']) != verdict(rm.get(i, {}).get('alone')):
                    notes.append(f'{n}: pass 1 differs on {i}: orig {ro[i]["alone"]}, re-run {rm.get(i, {}).get("alone")}')
        if not fin:
            for i in ro:
                if ro[i]['kept'] and verdict(ro[i].get('final')) != verdict(rm.get(i, {}).get('final')):
                    notes.append(f'{n}: final pass differs on {i}: orig {ro[i].get("final")}, re-run {rm[i].get("final")}')
        if not sw:
            for b in bs:
                if o['base'][b]['digest'] != m['base'][b]['digest']:
                    notes.append(f'{n}: as written on {b}: orig {o["base"][b]["digest"][:2]}, re-run {m["base"][b]["digest"][:2]}')
        if not dmin:
            for b in bs:
                if o['minimal'][b]['digest'] != m['minimal'][b]['digest']:
                    notes.append(f'{n}: smallest on {b}: orig {o["minimal"][b]["digest"][:2]}, re-run {m["minimal"][b]["digest"][:2]}')
        if o.get('warm') != m.get('warm') or o.get('warm_refused') != m.get('warm_refused'):
            notes.append(f'{n}: warm start differs: orig {o.get("warm") or o.get("warm_refused")}, '
                         f're-run {m.get("warm") or m.get("warm_refused")}')
        und = [i for i in rm if rm[i]['kept'] and rm[i].get('final') and rm[i]['final'][1] == 'LIMIT']
        if und:
            notes.append(f'{n}: kept as undecided (LIMIT) in the re-run: {und}')
    w('')
    if notes:
        w('## Differences and notes\n')
        for x in notes:
            w(f'- {x}')
    else:
        w('No differences: every field compared is identical.')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
