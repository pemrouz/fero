#!/usr/bin/env python3
"""report47.py: results/summary.md from results/runs.json (every run of run47.py).

One row per (rule set, rules dropped, R4 window, mode); one column per bound,
for each rung config. A cell is `ok` (every reachable state explored, no
property broken, every program can end), the properties broken with the length
of the shortest trace, or `LIMIT` (stopped at the state limit with no
counterexample: a partial check). States are summed per row.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DB = json.load(open(os.path.join(HERE, 'results', 'runs.json')))
ORDER = ['txn', 'txnb', 'txn1', 'txn1-2r', 'dedup', 'lockAA', 'lockBA', 'lockAB',
         'lockAA-row', 'lockBA-row', 'lockAB-row', 'dedup-v', 'lockAA-v', 'lockBA-v']


def cell(x):
    if x['fail']:
        return ', '.join(f'{p} {x["fail"][p][0]}' for p in sorted(x['fail']))
    if not x['complete']:
        return 'LIMIT'
    live = x.get('judged', {}).get('done')
    if live and live[1]:
        return f'stuck {live[1]}'
    return 'ok'


rows = {}
models = set()
for k, x in DB.items():
    model, cfg, rules, bound, _settings, mode, drop, allfails, W, limit = json.loads(k)
    models.add(model)
    rk = ('+'.join(rules) or 'none', ', '.join(drop), W, mode + (', every property' if allfails else ''))
    rows.setdefault(rk, {})[(cfg, bound)] = x

print('# E-47 summary (generated by report47.py from results/runs.json)')
print()
print(f'Model: models/memrung.py, sha256 prefix {", ".join(sorted(models))} (every run below used it).')
print()
print('Cells: `ok` = every reachable state explored, nothing broken, and every program can end; '
      '`P n` = property P broken, shortest trace n steps; `LIMIT` = stopped at the state limit with no '
      'counterexample (partial). Configs: PP both persisted, MP group A memory and B persisted, MM both '
      'memory (only A loses its tail). In `info` rows the properties are the losses the rung allows.')
for (rules, drop, W, mode) in sorted(rows, key=lambda r: (r[3].startswith('info'), r[0] != 'none', r[0], r[1], r[2], r[3])):
    cols = rows[(rules, drop, W, mode)]
    bounds = [b for b in ORDER if any(bb == b for _, bb in cols)]
    cfgs = sorted({c for c, _ in cols}, key=lambda c: ('PP', 'MP', 'MM').index(c))
    title = f'rules {rules}' + (f', dropped {drop}' if drop else '') + (f', R4 window {W}' if W != 2 else '') + \
        (f' ({mode} mode)' if mode != 'bug' else '')
    states = sum(x['states'] for x in cols.values())
    print()
    print(f'## {title} ({states:,} states in all)')
    print()
    print('| config | ' + ' | '.join(bounds) + ' |')
    print('|---|' + '---|' * len(bounds))
    for c in cfgs:
        print(f'| {c} | ' + ' | '.join(cell(cols[(c, b)]) if (c, b) in cols else '' for b in bounds) + ' |')
