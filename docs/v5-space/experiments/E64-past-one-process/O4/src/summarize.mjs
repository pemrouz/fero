// E-64 O4: results/summary.md from the JSON lines in results/. node src/summarize.mjs > results/summary.md
import { readFileSync, existsSync } from 'node:fs'
const R = new URL('../results/', import.meta.url)
const lines = (f) => (existsSync(new URL(f, R)) ? readFileSync(new URL(f, R), 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)) : [])
const fmt = (x) => (x === null || x === undefined ? '—' : typeof x === 'number' ? (Number.isInteger(x) ? x.toLocaleString('en-US') : x.toLocaleString('en-US', { maximumFractionDigits: 3 })) : String(x))
const range = (xs) => { const v = xs.filter((x) => typeof x === 'number'); if (!v.length) return '—'; const lo = Math.min(...v), hi = Math.max(...v); return lo === hi ? fmt(lo) : `${fmt(lo)} to ${fmt(hi)}` }
const loads = (rows) => rows.filter((r) => r.loadavg).map((r) => +r.loadavg.split(' ')[0])
const p = (s) => process.stdout.write(s + '\n')

function simTable(rows, title) {
  const rs = rows.filter((r) => r.run === 'sim')
  if (!rs.length) return
  p(`### ${title}\n`)
  p('| wire | groups | shards K | domain | down | barrier | planted | seeds × steps | failed | first failure | checks | rows checked | slot moves | router crashes | batches lost | zombies applied | shard crashes | shard moves | pictures (rows) | gaps | batches | markers | messages a write | cross-shard a write | rows counted twice or nowhere (checks with any) | positions behind a shard, mean (lean: a slot advances only with a part for that shard) | barriers: done / wrong / stuck, mean and max wait (steps) |')
  p('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
  for (const r of rs) {
    const ff = r.firstFail ? `seed ${r.firstFail.seed}: ${r.firstFail.where}${r.firstFail.step ? ' at step ' + r.firstFail.step : ''}` : '—'
    const bar = r.barrier ? `${fmt(r.barriers)} / ${fmt(r.barrierBad)} / ${fmt(r.barrierStuck)}, ${fmt(+(r.barrierSteps / Math.max(1, r.barriers)).toFixed(1))} and ${fmt(r.barrierMaxSteps)}` : '—'
    p(`| ${r.wire ?? 'full'} | ${r.groups} | ${r.K} | ${r.dom} | ${r.down ? 'yes' : 'no'} | ${r.barrier || '—'} | ${r.mutate ?? '—'} | ${fmt(r.seeds)} × ${fmt(r.stepsPerSeed)} | ${fmt(r.failed)} | ${ff} | ${fmt(r.checks)} | ${fmt(r.rowsChecked)} | ${fmt(r.w_moves)} | ${fmt(r.routerCrashes)} | ${fmt(r.lostBatches)} | ${fmt(r.zombiesDelivered)} | ${fmt(r.shardCrashes)} | ${fmt(r.shardMoves)} | ${fmt(r.pictures)} (${fmt(r.pictureRows)}) | ${fmt(r.gap)} | ${fmt(r.batches)} | ${fmt(r.markers)} | ${fmt(+(r.msgs / r.w_entries).toFixed(3))} | ${fmt(+(r.crossShard / r.w_entries).toFixed(3))} | ${fmt(r.torn)} = ${fmt(+(1e3 * r.torn / Math.max(1, r.rowsChecked)).toFixed(2))} per 1,000 rows checked (${fmt(r.tornChecks)}) | ${fmt(+(r.lag / Math.max(1, r.checks * r.K)).toFixed(2))} | ${bar} |`)
  }
  p('')
}

p('# E-64 O4: results\n')
p('Generated by `src/summarize.mjs` from `results/*.jsonl`. Ranges are over the three timed runs.\n')
simTable(lines('sims.jsonl'), 'Seeded runs: the design')
simTable(lines('mutants.jsonl'), 'Planted bugs (each must fail at least 100 of 1,000 seeds, or be shown not needed)')
simTable(lines('long.jsonl'), 'Long runs')

const t = lines('timing.jsonl')
const by = (f) => t.filter((r) => !r.loadavg && f(r))
if (t.length) {
  p('### Timed costs (three runs, each process alone under the timing lock)\n')
  p('A source copy\'s fold in lanes of 256 records, with the router (K = 16 shards), ns a record:\n')
  p('| rows | plain fold | + router (messages as objects) | + encoded, a frame per shard per lane | + encoded, a frame per 256 messages | messages a record | cross-shard a record | bytes a record (encoded) |')
  p('|---|---|---|---|---|---|---|---|')
  for (const n of [100000, 1000000]) {
    const g = (v) => by((r) => r.bench === 'route' && r.rows === n && r.variant === v)
    const e = g('encode256')
    p(`| ${fmt(n)} | ${range(g('plain').map((r) => r.ns_per_record))} | ${range(g('route').map((r) => r.ns_per_record))} | ${range(g('encode').map((r) => r.ns_per_record))} | ${range(e.map((r) => r.ns_per_record))} | ${range(g('route').map((r) => r.msgs_per_record))} | ${range(g('route').map((r) => r.cross_shard_per_record))} | ${range(e.map((r) => r.msg_bytes_per_record))} |`)
  }
  p('\nOne view shard against R0\'s one store, ns a message (shard) or a record (R0); heap a row held:\n')
  p('| rows of the resource | view | R0: fold only | R0: fold and view | R0: heap a row (+ view) | shard of 16: ns a message | shard of 16: rows held | shard of 16: heap a row | shard of 16: messages a source record | shard of 4 (sum): ns a message | shard of 4: heap a row |')
  p('|---|---|---|---|---|---|---|---|---|---|---|')
  for (const n of [100000, 1000000]) for (const v of ['sum', 'full']) {
    const r0 = by((r) => r.bench === 'r0' && r.rows === n && r.view === v)
    const s16 = by((r) => r.bench === 'shard' && r.rows === n && r.view === v && r.K === 16)
    const s4 = v === 'sum' ? by((r) => r.bench === 'shard' && r.rows === n && r.view === 'sum' && r.K === 4) : []
    p(`| ${fmt(n)} | ${v} | ${range(r0.map((r) => r.ns_fold))} | ${range(r0.map((r) => r.ns_fold_and_view))} | ${range(r0.map((r) => r.heap_b_per_row))} (+${range(r0.map((r) => r.view_heap_b_per_row))}) | ${range(s16.map((r) => r.ns_per_msg))} | ${range(s16.map((r) => r.rows_held))} | ${range(s16.map((r) => r.heap_b_per_row))} | ${range(s16.map((r) => r.msgs_per_source_record))} | ${range(s4.map((r) => r.ns_per_msg))} | ${range(s4.map((r) => r.heap_b_per_row))} |`)
  }
  p('\nA picture\'s scan at a copy (every row of the store, keep one shard\'s of 16):\n')
  p('| rows | ms a scan | ns a row |')
  p('|---|---|---|')
  for (const n of [100000, 1000000]) { const s = by((r) => r.bench === 'scan' && r.rows === n); p(`| ${fmt(n)} | ${range(s.map((r) => r.ms_per_scan))} | ${range(s.map((r) => r.ns_per_row))} |`) }
  const la = loads(t)
  if (la.length) p(`\nOne-minute load average at process start: ${fmt(Math.min(...la))} to ${fmt(Math.max(...la))}.`)
  p('')
}
const b = lines('bytes.jsonl').filter((r) => r.bench === 'bytes')
if (b.length) {
  p('### Bytes a record (fero v4\'s codec; the log in frames of 256 records, messages in frames of 256 per shard)\n')
  p('| shards K | the log | routed messages, all shards | messages a record | cross-shard a record | messages a frame |')
  p('|---|---|---|---|---|---|')
  for (const r of b) p(`| ${r.K} | ${fmt(r.log_b_per_record)} | ${fmt(r.msg_b_per_record)} | ${fmt(r.msgs_per_record)} | ${fmt(r.cross_shard_per_record)} | ${fmt(r.msgs_per_frame)} |`)
  p('')
}
