#!/usr/bin/env python3
"""E-35 tables from results/runs.jsonl and results/probe.jsonl (median of runs, range in brackets)."""
import json, os, statistics
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
rows = [json.loads(l) for l in open(os.path.join(HERE, "results", "runs.jsonl")) if l.strip()]
by = defaultdict(list)
for r in rows: by[r["tag"]].append(r)
med = statistics.median

def cls(r, name):
    for c in r["classes"]:
        if c["name"] == name: return c
    return None

def vals(tag, name, key):
    return [cls(r, name)[key] for r in by.get(tag, []) if cls(r, name) and cls(r, name)[key] is not None]

def cell(tag, name, key):
    xs = vals(tag, name, key)
    if not xs: return "-"
    m = med(xs); s = f"{m:.2f}"
    if len(xs) > 1: s += f" [{min(xs):.2f}-{max(xs):.2f}]"
    return s + ("" if len(xs) >= 3 else f" (n={len(xs)})")

def ratio(t1, t0, name, key="p99"):
    a, b = vals(t1, name, key), vals(t0, name, key)
    return f"{med(a)/med(b):.2f}×" if a and b else "-"

V = ["base", "blob", "cap", "rr", "own"]
VN = {"base": "one journal, FIFO, uncapped (E-12 a)", "blob": "big records in a side file, pointer in the journal",
      "cap": "batches capped at 64 KiB, FIFO", "rr": "capped at 64 KiB, round robin across groups", "own": "one journal per group or tenant (E-12 b)"}
out = []; P = out.append
P("# E-35 tables (generated by summarize.py)\n")
P("Median of 3 runs, range in brackets; latency in ms (commit p99 from ideal arrival to durable). Node 22, E-12's journal (`../E12-journal/ts/journal.ts`).\n")
P("## (a) SC-15: one partition writes 1 MiB records 10 times a second beside 16 partitions of 100 B writers (10,000/s)\n")
P("| variant | victim p99 alone | victim p99 beside 1 MiB | ratio (bar ≤ 1.2×) | victim p50 alone / beside | big record p99 |")
P("|---|---|---|---|---|---|")
for v in V:
    t0, t1 = f"a/{v}/alone", f"a/{v}/big"
    if t0 not in by and t1 not in by: continue
    P(f"| {v}: {VN[v]} | {cell(t0,'victim','p99')} | {cell(t1,'victim','p99')} | {ratio(t1,t0,'victim')} | {cell(t0,'victim','p50')} / {cell(t1,'victim','p50')} | {cell(t1,'big','p99')} |")
P("\nRatio against the base variant's victim alone (does the variant cost the victims anything by itself):\n")
P("| variant | victim p99 alone ÷ base alone | victim p99 beside ÷ base alone |")
P("|---|---|---|")
for v in V:
    P(f"| {v} | {ratio(f'a/{v}/alone','a/base/alone','victim')} | {ratio(f'a/{v}/big','a/base/alone','victim')} |")

for q in (10, 40):
    P(f"\n## (b) SC-11: 100 tenants on one log-tier process; tenant A at {q} MiB/s; tenant B at 100 writes/s; 98 others at 10 writes/s each\n")
    P("| variant | B p99 alone | B p99, A in 1 MiB records | ratio | B p99, A in 64 KiB records | ratio (bar ≤ 1.1×) | others p99 alone / A 1 MiB / A 64 KiB | A p99 (1 MiB / 64 KiB) |")
    P("|---|---|---|---|---|---|---|---|")
    for v in V:
        t0, t1, t2 = f"b/{v}/alone", f"b{q}/{v}/A-1MiB", f"b{q}/{v}/A-64KiB"
        if t1 not in by and t2 not in by: continue
        P(f"| {v} | {cell(t0,'B','p99')} | {cell(t1,'B','p99')} | {ratio(t1,t0,'B')} | {cell(t2,'B','p99')} | {ratio(t2,t0,'B')} | {cell(t0,'others','p99')} / {cell(t1,'others','p99')} / {cell(t2,'others','p99')} | {cell(t1,'A','p99')} / {cell(t2,'A','p99')} |")
    P("\nAll light tenants together (B and the 98 others; more samples, so a steadier p99): ratio of p99 beside A to alone.\n")
    P("| variant | A in 1 MiB | A in 64 KiB |")
    P("|---|---|---|")
    for v in V:
        P(f"| {v} | {ratio(f'b{q}/{v}/A-1MiB', f'b/{v}/alone', 'others')} | {ratio(f'b{q}/{v}/A-64KiB', f'b/{v}/alone', 'others')} |")

pp = os.path.join(HERE, "results", "probe.jsonl")
if os.path.exists(pp):
    pr = [json.loads(l) for l in open(pp) if l.strip()]
    P("\n## The critic's probe, re-run (64 × 100 B per batch; `mixed` adds one 1 MiB record to every 10th batch; 1,000 batches)\n")
    P("| run | small p99 ms | mixed p99 ms | ratio | load |")
    P("|---|---|---|---|---|")
    for run in sorted({p["run"] for p in pr}):
        s = [p for p in pr if p["run"] == run and p["mode"] == "small"]; m = [p for p in pr if p["run"] == run and p["mode"] == "mixed"]
        if s and m: P(f"| {run} | {s[0]['p99_ms']} | {m[0]['p99_ms']} | {float(m[0]['p99_ms'])/float(s[0]['p99_ms']):.1f}× | {s[0]['loadavg'].split()[0]} |")
las = [float(r["loadavg"].split()[0]) for r in rows]
if las:
    P(f"\n{len(rows)} runs; 1-minute load average min {min(las):.2f}, median {med(las):.2f}, max {max(las):.2f}; other busy cores in the window: median {med([r['other_cores'] for r in rows]):.2f}.")
print("\n".join(out))
