// E-65 X4: results/summary.md from the JSON lines. With --quick FILE: a pass/fail line per part, exit 1 on a miss.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
const quick = process.argv[2] === '--quick'
const lines = (f) => (existsSync(f) ? readFileSync(f, 'utf8').trim().split('\n').filter(Boolean).map((l) => JSON.parse(l)) : [])
const pct = (x) => (x === undefined ? '—' : (100 * x).toFixed(x < 0.001 ? 4 : x < 0.01 ? 3 : 2) + ' %')
const rng = (xs, d = 2) => { xs = xs.filter((x) => x !== undefined); if (!xs.length) return '—'; const a = Math.min(...xs), b = Math.max(...xs); return a.toFixed(d) === b.toFixed(d) ? a.toFixed(d) : `${a.toFixed(d)} to ${b.toFixed(d)}` }

if (quick) {
  const all = lines(process.argv[3])
  let bad = 0
  for (const j of all) {
    if (j.part === 'sim') {
      const ok = j.mutate === 'none' ? j.failed === 0 : j.failed > 0
      if (!ok) bad++
      console.log(`${ok ? 'ok  ' : 'MISS'} sim ${j.mutate}: ${j.failed}/${j.seeds} seeds failed, ${j.checks} checks, ${j.exactChecks} exact`)
    } else if (j.part === 'static' || j.part === 'churn') {
      const ok = j.dd.rel <= 0.01 * (1 + 1e-9)
      if (!ok) bad++
      console.log(`${ok ? 'ok  ' : 'MISS'} ${j.part}: DD max relative error ${pct(j.dd.rel)} (bound 1 %)`)
    } else console.log(`ok   ${j.part || j.cell}`)
  }
  process.exit(bad ? 1 : 0)
}

const R = new URL('../results/', import.meta.url).pathname
const out = ['# E-65 X4 results', '', 'Generated by `src/summarize.mjs` from `sim.jsonl`, `accuracy.jsonl` and `bench.jsonl`. Timed cells: the range over three runs, each run alone under the timing lock; inside a run, the median of 5 rounds after a warm-up.', '']

const sim = lines(R + 'sim.jsonl')
out.push('## Seeded runs *(checked)*', '', '| code | a | slots | seeds | failed | commits | slot moves | resyncs | checks | exact checks | re-bands | one-time reads of 4 ranks (ranks that needed a split) | first failure |', '|---|---|---|---|---|---|---|---|---|---|---|---|---|')
for (const j of sim) {
  if (j.failed === undefined || j.part !== 'sim') continue
  const f = j.fails[0]
  out.push(`| ${j.mutate} | ${j.alpha} | ${j.S} | ${j.seeds} | ${j.failed} | ${j.commits} | ${j.moves} | ${j.resyncs} | ${j.checks} | ${j.exactChecks} | ${j.rebands} | ${j.onetime} (${j.onetimeSplit}) | ${f ? `seed ${f.seed} (${f.dist}): ${f.why.slice(0, 60)}` : ''} |`)
}
const acc = lines(R + 'accuracy.jsonl')
const mx = (xs, k, s) => Math.max(...xs.map((x) => (x[k] ? x[k][s] : 0)))
out.push('', '## Accuracy, one-time inserts *(counted; worst of 3 seeds over p50, p90, p99, p99.9)*', '', 'Relative error: |answer − truth| / |truth|. Rank error: how far the answer\'s rank is from the asked rank, as a share of the count. DD a = 1 %, KLL k = 200, t-digest default compression. The npm DDSketch ran only on the mixes with no zeros or negatives; there it gave the own histogram\'s answers to the last digit.', '', '| mix | rows | DD rel | DD rank | KLL rel | KLL rank | KLL 16 merged rank | npm DDSketch rel | npm t-digest rel | npm t-digest rank | DD buckets | KLL items | t-digest centroids |', '|---|---|---|---|---|---|---|---|---|---|---|---|---|')
const st = acc.filter((j) => j.part === 'static')
for (const key of [...new Set(st.map((j) => `${j.dist}|${j.n}`))]) {
  const xs = st.filter((j) => `${j.dist}|${j.n}` === key)
  const x = xs[0]
  out.push(`| ${x.dist} | ${x.n} | ${pct(mx(xs, 'dd', 'rel'))} | ${pct(mx(xs, 'dd', 'rank'))} | ${pct(mx(xs, 'kll', 'rel'))} | ${pct(mx(xs, 'kll', 'rank'))} | ${pct(mx(xs, 'kllMerged16', 'rank'))} | ${x.libDD && x.dist !== 'ints' && x.dist !== 'wide' ? pct(mx(xs, 'libDD', 'rel')) : '—'} | ${x.libTD ? pct(mx(xs, 'libTD', 'rel')) : '—'} | ${x.libTD ? pct(mx(xs, 'libTD', 'rank')) : '—'} | ${Math.max(...xs.map((j) => j.ddBuckets))} | ${Math.max(...xs.map((j) => j.kllItems))} | ${x.tdCentroids ?? '—'} |`)
}
const ch = acc.filter((j) => j.part === 'churn')
out.push('', '## Accuracy under updates and removes *(counted; 100,000 live values, the mix drifting 3 sigma)*', '', '| updates per row | c | DD rel | DD rank | KLL turnstile rel | rank | KLL rebuilt rel | rank | rebuild items per write | KLL ignoring removes rank |', '|---|---|---|---|---|---|---|---|---|---|')
for (const key of [...new Set(ch.map((j) => `${j.updatesPerRow}|${j.c}`))]) {
  const xs = ch.filter((j) => `${j.updatesPerRow}|${j.c}` === key), x = xs[0]
  out.push(`| ${x.updatesPerRow} | ${x.c} | ${pct(mx(xs, 'dd', 'rel'))} | ${pct(mx(xs, 'dd', 'rank'))} | ${pct(mx(xs, 'turnstile', 'rel'))} | ${pct(mx(xs, 'turnstile', 'rank'))} | ${pct(mx(xs, 'rebuild', 'rel'))} | ${pct(mx(xs, 'rebuild', 'rank'))} | ${x.rebuildItemsPerWrite.toFixed(2)} | ${pct(mx(xs, 'ignoreRemoves', 'rank'))} |`)
}
const bd = acc.filter((j) => j.part === 'band')
out.push('', '## Exact values the live form holds at the asker *(counted; the bucket of the rank and 2 non-empty buckets each side)*', '', '| mix | rows | a | buckets in use | held for p50 | share | held for p99 | share |', '|---|---|---|---|---|---|---|---|')
for (const j of bd) out.push(`| ${j.dist} | ${j.n} | ${j.alpha} | ${j.buckets} | ${j.band50} | ${pct(j.share50)} | ${j.band99} | ${pct(j.share99)} |`)

const be = lines(R + 'bench.jsonl')
out.push('', '## Timed cells *(measured)*', '')
const cells = [...new Set(be.map((j) => [j.cell, j.n, j.g, j.alpha, j.mode].join('|')))]
for (const c of cells) {
  const xs = be.filter((j) => [j.cell, j.n, j.g, j.alpha, j.mode].join('|') === c), x = xs[0]
  const keys = Object.keys(x).filter((k) => !['cell', 'n', 'g', 'alpha', 'mode', 'loadavg', 'w', 'cap'].includes(k))
  const parts = keys.map((k) => typeof x[k] === 'object' ? `${k} ${JSON.stringify(x[k])}` : `${k} ${rng(xs.map((j) => j[k]), Number.isInteger(x[k]) ? 0 : 2)}`)
  out.push(`- **${x.cell}** (n ${x.n}, g ${x.g}, a ${x.alpha}${x.mode ? ', ' + x.mode : ''}; ${xs.length} runs; load ${rng(xs.map((j) => j.loadavg[0]))}): ${parts.join('; ')}`)
}
writeFileSync(R + 'summary.md', out.join('\n') + '\n')
console.log('wrote results/summary.md')
