#!/usr/bin/env python3
"""E-04: fold results/*.jsonl into results/tables.md. For timing rows: the median over the 3 runs of
each run's median, and (min-max of the run medians). python3 -I summarize.py"""
import json, os, statistics, collections

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, 'results')

def lines(name):
    p = os.path.join(R, name)
    if not os.path.exists(p): return [], []
    runs, rows, cur = [], [], None
    for l in open(p):
        l = l.strip()
        if not l.startswith('{'): continue
        o = json.loads(l)
        if 'loadavg' in o: cur = o['run']; runs.append(o); continue
        o['_run'] = cur; rows.append(o)
    return runs, rows

def fmt(x):
    if x is None: return ''
    if isinstance(x, int) and abs(x) >= 1000: return f'{x:,}'
    if abs(x) >= 100: return f'{x:,.0f}'
    if abs(x) >= 10: return f'{x:.1f}'
    if abs(x) >= 0.1: return f'{x:.2f}'
    return f'{x:.3f}'

def cell(xs):
    m = statistics.median(xs)
    return fmt(m) if min(xs) == max(xs) else f'{fmt(m)} ({fmt(min(xs))}-{fmt(max(xs))})'

out = ['# E-04 tables (generated by summarize.py)', '']
runs, rows = lines('guard.jsonl')
if rows:
    out += ['### The guard: TS twin vs WASM twin, same seeded inputs', '', '| run | seeds | kernel events | seeds that differ | first differing seed (step) | median first differing step | monitor violations | kernel errors |', '|---|---|---|---|---|---|---|---|']
    for o in rows:
        f = o.get('first') or {}
        out.append(f"| {o['label']} | {o['seeds']} | {o['events']:,} | {o['seedsDiffer']} | {('%s (%s of %s)' % (f.get('seed'), f.get('step'), f.get('ofSteps'))) if f else ''} | {o.get('medianFirstDiffStep') if o.get('medianFirstDiffStep') is not None else ''} | {o['monitorViolations']} | {o['kernelErrors']} |")
    out.append('')
runs, rows = lines('test01.jsonl')
if rows:
    out.append('load averages at start: ' + ', '.join(r['loadavg'].split()[0] for r in runs) + '\n')
    g = collections.OrderedDict()
    for o in [o for o in rows if o['measure'] == 'chaos-200']: g.setdefault(o['kernel'], []).append(o)
    out += ['### 200 chaos seeds (TEST-01 bar: <= 1 s)', '', '| kernel | ms for 200 seeds | events | ns per event | monitor violations |', '|---|---|---|---|---|']
    for k, os_ in g.items():
        out.append(f"| {k} | {cell([o['ms'] for o in os_])} | {os_[0]['events']:,} | {cell([o['nsPerEvent'] for o in os_])} | {sum(o['violations'] for o in os_)} |")
    out.append('')
    g = collections.OrderedDict()
    for o in [o for o in rows if o['measure'] == 'fresh node + scenario']: g.setdefault(o['kernel'], []).append(o)
    out += ['### A fresh solo node plus a scenario (TEST-01 bar: <= 5 ms)', '', '| kernel | p50 ms | p99 ms | max ms (median of runs) |', '|---|---|---|---|']
    for k, os_ in g.items():
        out.append(f"| {k} | {cell([o['p50ms'] for o in os_])} | {cell([o['p99ms'] for o in os_])} | {cell([o['maxms'] for o in os_])} |")
    out.append('')
    g = collections.OrderedDict()
    for o in [o for o in rows if o['measure'] == 'replay']: g.setdefault(o['kernel'], []).append(o)
    nruns, nrows = lines('replay-native.jsonl')
    out += ['### Replay of 200 recorded K seeds, no driver (ns per event)', '', '| how | ns per event | events |', '|---|---|---|']
    for k, os_ in g.items():
        out.append(f"| {k} | {cell([o['ns'] for o in os_])} | {os_[0]['events']:,} |")
    if nrows:
        out.append(f"| K native Rust (no WASM, no JS) | {cell([o['ns'] for o in nrows])} | {nrows[0]['events']:,} |")
    out.append('')
    g = collections.OrderedDict()
    for o in [o for o in rows if o['measure'] == 'wasm-setup']: g.setdefault(o['what'], []).append(o)
    sz = [o for o in rows if o['measure'] == 'wasm-size']
    out += ['### WASM set-up', '', '| what | µs |', '|---|---|']
    for k, os_ in g.items():
        out.append(f"| {k} | {cell([o['us'] for o in os_])} |")
    if sz: out.append(f"\nModule sizes: K {sz[0]['k']:,} bytes; raft-rs {sz[0]['raft']:,} bytes.")
    out.append('')
open(os.path.join(R, 'tables.md'), 'w').write('\n'.join(out))
print('\n'.join(out))
