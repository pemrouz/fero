#!/usr/bin/env python3
"""E-11 tables from results/runs.jsonl: median of the runs, range in brackets."""
import json, sys, statistics
from collections import defaultdict

rows = [json.loads(l) for l in open(sys.argv[1]) if l.strip()]
by = defaultdict(list)
for r in rows:
    by[r["tag"]].append(r)
med = lambda xs: statistics.median(xs) if xs else None

def f(v, k):
    if v is None: return "-"
    if k == "pct": return f"{v*100:.2f}%" if v < 0.1 else f"{v*100:.0f}%"
    if k == "int": return f"{v:,.0f}"
    if k == "mb": return f"{v/1024:.1f}"
    if k == "kb": return f"{v:.1f}"
    if k == "ms": return f"{v:.2f}" if v < 10 else f"{v:.0f}"
    return str(v)

def cell(tag, key, k):
    rs = by.get(tag)
    if not rs: return "-"
    xs = [r[key] for r in rs]
    s = f(med(xs), k)
    if len(xs) > 1: s += f" [{f(min(xs),k)}-{f(max(xs),k)}]"
    return s + ("" if len(xs) >= 3 else f" (n={len(xs)})")

def mv(tag, key):
    rs = by.get(tag)
    return med([r[key] for r in rs]) if rs else None

def mvh(tag):
    rs = by.get(tag)
    if not rs: return None
    xs = [sum(nd["heap_kb"] for nd in r["nodes"]) / 3 for r in rs]
    return med(xs) if xs and min(xs) > 0 else None

out = []; P = out.append
P("# E-11 tables (generated by summarize.py from runs.jsonl)\n")
P("Median of 3 runs, range in brackets. Per process (each of the 3 processes hosts one replica of every group): `CPU` = share of one core over the 6 s window (mean of the 3 processes); `frames/s` = wire frames sent per process; `RSS` = resident memory per process at the end of the window, MB. `KB/group` = (RSS at N - RSS at N=10) / (N - 10).\n")
P("## Idle\n")
P("| build | mode | N | CPU per process | frames/s per process | messages/s per process | RSS MB | KB/group (RSS) | KB/group (heap after GC) | groups awake at end | leaders per process |")
P("|---|---|---|---|---|---|---|---|---|---|---|")
for impl in ("go", "rs", "ts"):
    for m in ("tick100", "tick500", "quiet500"):
        base = mv(f"{impl}/{m}/n10/r0/h1", "rss_kb_mean")
        hbase = mvh(f"{impl}/{m}/n10/r0/h1")
        for n in (10, 100, 1000, 2000, 10000):
            t = f"{impl}/{m}/n{n}/r0/h1"
            if t not in by: continue
            rss = mv(t, "rss_kb_mean")
            kbg = (rss - base) / (n - 10) if base is not None and n > 10 else None
            awake = med([sum(r["awake_end"]) / 3 for r in by[t]])
            h = mvh(t); hkbg = (h - hbase) / (n - 10) if h is not None and hbase is not None and h > 0 and n > 10 else None
            lead = "/".join(str(x) for x in by[t][0]["leaders"])
            P(f"| {impl} | {m} | {n:,} | {cell(t,'cores_mean','pct')} | {cell(t,'frames_s_mean','int')} | {cell(t,'msgs_s_mean','int')} | {cell(t,'rss_kb_mean','mb')} | {f(kbg,'kb')} | {f(hkbg,'kb')} | {awake:,.0f} | {lead} |")
P("\n## Busy: 10,000 writes/s of 100 B over the cluster (quiet mode on)\n")
P("`hot` = the share of groups that get writes. `p99` = commit latency on the proposing leader (ms), the worst of the 3 processes; `p50` = weighted mean of the 3. `fsyncs/s` per process.\n")
P("| build | mode | N | hot | commits/s | p50 ms | p99 ms | CPU per process | frames/s per process | fsyncs/s | RSS MB |")
P("|---|---|---|---|---|---|---|---|---|---|---|")
for impl in ("go", "rs", "ts"):
    for m in ("quiet500", "tick100"):
        for hot in (1, 0.01):
            for n in (1, 10, 16, 100, 1000, 2000, 10000):
                t = f"{impl}/{m}/n{n}/r10000/h{hot}"
                if t not in by: continue
                P(f"| {impl} | {m} | {n:,} | {hot:g} | {cell(t,'commits_s','int')} | {cell(t,'p50_wmean','ms')} | {cell(t,'p99_max','ms')} | {cell(t,'cores_mean','pct')} | {cell(t,'frames_s_mean','int')} | {cell(t,'fsyncs_s_mean','int')} | {cell(t,'rss_kb_mean','mb')} |")
P("\n## Load average at the start of each run\n")
las = [float(r["loadavg"].split()[0]) for r in rows]
P(f"{len(rows)} runs; 1-minute load average min {min(las):.2f}, median {statistics.median(las):.2f}, max {max(las):.2f}.")
print("\n".join(out))
