#!/usr/bin/env python3
"""E-12 tables from results/runs.jsonl: median of the runs, range in brackets."""
import json, sys, statistics
from collections import defaultdict

rows = [json.loads(l) for l in open(sys.argv[1]) if l.strip()]
by = defaultdict(list)
for r in rows:
    by[r["tag"]].append(r)

def med(xs):
    xs = [x for x in xs if x is not None]
    return statistics.median(xs) if xs else None

def fmt(v, kind):
    if v is None: return "-"
    if kind == "rate": return f"{v/1e6:.2f}M" if v >= 1e6 else (f"{v/1e3:.0f}k" if v >= 1e4 else f"{v:.0f}")
    if kind == "ms": return f"{v:.2f}" if v < 10 else f"{v:.0f}"
    if kind == "us": return f"{v:.1f}" if v < 100 else f"{v:.0f}"
    return str(v)

def cell(tag, key, kind):
    rs = by.get(tag)
    if not rs: return "-"
    xs = [r[key] for r in rs if r.get(key) is not None]
    if not xs: return "-"
    m = med(xs)
    s = fmt(m, kind)
    if len(xs) > 1: s += f" [{fmt(min(xs), kind)}-{fmt(max(xs), kind)}]"
    return s + ("" if len(xs) >= 3 else f" (n={len(xs)})")

def mval(tag, key):
    rs = by.get(tag)
    return med([r[key] for r in rs]) if rs else None

out = []
P = out.append
P("# E-12 tables (generated by summarize.py from runs.jsonl)\n")
P("Median of 3 runs, range in brackets. `appends/s` = records made durable per second in the 6 s window; `p99` = commit latency (ms) from each record's ideal arrival to the fdatasync that covers it; `CPU` = µs of CPU (all threads of the process) per durable append; `rec/sync` = records per fdatasync batch (per window for c). Loads: fixed offered rates and `max` (up to 32 MiB of records in flight, as E-02). Growing files, 4 sync threads, unless the section says otherwise.\n")
for impl in ("rs", "ts"):
    for pre, pool, title in ((0, 4, "growing files, 4 sync threads"), (1, 4, "preallocated zero-filled segments, 4 sync threads"), (0, 32, "growing files, 32 sync threads"), (0, "G", "growing files, one sync thread per group")):
        if False:
            pass
        elif pool == "G":
            tags = [t for t in by if t.startswith(impl + "/") and t.count("/") == 5 and t.split("/")[5] == "t" + t.split("/")[2]]
        else:
            tags = [t for t in by if t.startswith(impl + "/") and t.endswith(f"/p{pre}/t{pool}")]
        if not tags: continue
        P(f"\n## {'Rust' if impl == 'rs' else 'Node'}: {title}\n")
        P("| groups | load | mode | appends/s | fsyncs/s | p99 ms | p99.9 ms | CPU µs/append | rec/sync |")
        P("|---|---|---|---|---|---|---|---|---|")
        for g in (1, 16, 256, 2000):
            for load in ("10000", "50000", "200000", "max"):
                for mode in ("a", "b", "c"):
                    t = f"{impl}/{mode}/{g}/{load}/p{pre}/t{g if pool == 'G' else pool}"
                    if t not in by or t not in tags: continue
                    P(f"| {g} | {load} | {mode} | {cell(t,'appends_s','rate')} | {cell(t,'fsyncs_s','rate')} | {cell(t,'p99','ms')} | {cell(t,'p999','ms')} | {cell(t,'cpu_us_per_append','us')} | {fmt(mval(t,'recs_per_batch'),'us')} |")

P("\n## The threshold: per-group files against one journal\n")
P("Ratio of medians, (b)/(a) and (c)/(a). For `max` the ratio is of appends/s (higher is better; the bar is ≥ 0.8). For fixed rates the ratio is of p99 (lower is better) and `kept` says whether the mode kept up with the offered rate (≥ 98%).\n")
P("| build | files | groups | load | b/a appends | c/a appends | b/a p99 | c/a p99 | kept a/b/c |")
P("|---|---|---|---|---|---|---|---|---|")
for impl in ("rs", "ts"):
    for pre, pool in ((0, 4), (1, 4), (0, 32), (0, "G")):
        for g in (1, 16, 256, 2000):
            for load in ("10000", "50000", "200000", "max"):
                pl = g if pool == "G" else pool
                if pool == "G" and g < 256: continue
                ta = f"{impl}/a/{g}/{load}/p{pre}/t4"
                tb = f"{impl}/b/{g}/{load}/p{pre}/t{pl}"
                tc = f"{impl}/c/{g}/{load}/p{pre}/t{pl}"
                if tb not in by and tc not in by: continue
                if ta not in by: continue
                aa, pa = mval(ta, "appends_s"), mval(ta, "p99")
                def ratio(t, k, base):
                    v = mval(t, k) if t in by else None
                    return f"{v/base:.2f}" if v is not None and base else "-"
                def kept(t):
                    if t not in by: return "-"
                    if load == "max": return "·"
                    return "yes" if mval(t, "appends_s") >= 0.98 * float(load) else "NO"
                lab = ("grow" if pre == 0 else "prealloc") + ("" if pool == 4 else (", 1 thr/group" if pool == "G" else f", {pool} thr"))
                P(f"| {impl} | {lab} | {g} | {load} | {ratio(tb,'appends_s',aa)} | {ratio(tc,'appends_s',aa)} | {ratio(tb,'p99',pa)} | {ratio(tc,'p99',pa)} | {kept(ta)}/{kept(tb)}/{kept(tc)} |")

st = sorted({t for t in by if t.endswith("/s4")})
if st:
    P("\n## One journal striped over 4 files (Rust; each file has its own flush thread; group g goes to file g % 4)\n")
    P("| groups | load | appends/s | fsyncs/s | p99 ms | p99.9 ms | CPU µs/append | vs one journal: appends | vs one journal: p99 | vs b (4 thr): appends | vs b (4 thr): p99 |")
    P("|---|---|---|---|---|---|---|---|---|---|---|")
    for g in (16, 256, 2000):
        for load in ("10000", "50000", "200000", "max"):
            t = f"rs/a/{g}/{load}/p0/t4/root/s4"
            t = t if t in by else f"rs/a/{g}/{load}/p0/t4/s4"
            if t not in by: continue
            ta, tb = f"rs/a/{g}/{load}/p0/t4", f"rs/b/{g}/{load}/p0/t4"
            r = lambda x, y, k: f"{mval(x,k)/mval(y,k):.2f}" if y in by and mval(y,k) else "-"
            P(f"| {g} | {load} | {cell(t,'appends_s','rate')} | {cell(t,'fsyncs_s','rate')} | {cell(t,'p99','ms')} | {cell(t,'p999','ms')} | {cell(t,'cpu_us_per_append','us')} | {r(t,ta,'appends_s')} | {r(t,ta,'p99')} | {r(t,tb,'appends_s')} | {r(t,tb,'p99')} |")

fsr = sorted({t for t in by if t.endswith("/ext4j") or t.endswith("/xfs")})
if fsr:
    P("\n## Other filesystems on the same disk (Rust; 4 GiB loop filesystems with direct I/O; `max` on preallocated segments)\n")
    P("| fs | groups | load | mode | appends/s | fsyncs/s | p99 ms | CPU µs/append | b or c ÷ a (appends at max, p99 at 50k) |")
    P("|---|---|---|---|---|---|---|---|---|")
    for fs in ("ext4j", "xfs"):
        for g in (256, 2000):
            for load, pre in (("50000", 0), ("max", 1)):
                for mode in ("a", "b", "c"):
                    t = f"rs/{mode}/{g}/{load}/p{pre}/t4/{fs}"
                    if t not in by: continue
                    ta = f"rs/a/{g}/{load}/p{pre}/t4/{fs}"
                    k = "appends_s" if load == "max" else "p99"
                    rr = f"{mval(t,k)/mval(ta,k):.2f}" if mode != "a" and ta in by else ""
                    P(f"| {fs} | {g} | {load} | {mode} | {cell(t,'appends_s','rate')} | {cell(t,'fsyncs_s','rate')} | {cell(t,'p99','ms')} | {cell(t,'cpu_us_per_append','us')} | {rr} |")

P("\n## Load average at the start of each run\n")
las = [float(r["loadavg"].split()[0]) for r in rows]
P(f"{len(rows)} runs; 1-minute load average min {min(las):.2f}, median {statistics.median(las):.2f}, max {max(las):.2f}. `other_cores` (busy cores outside this process during the window): median {statistics.median([r['other_cores'] for r in rows]):.2f}, max {max(r['other_cores'] for r in rows):.2f}.")
print("\n".join(out))
