// E-67: the tables. node bench/summarize.mjs results > results/summary.md
import { readFileSync, existsSync } from 'node:fs'
const dir = process.argv[2] ?? 'results'
const lines = (f) => (existsSync(dir + '/' + f) ? readFileSync(dir + '/' + f, 'utf8').split('\n').filter((l) => l.startsWith('{')).map((l) => JSON.parse(l)) : [])
const sim = lines('sim.jsonl'), bench = lines('bench.jsonl')
const f2 = (x) => (Math.abs(x) >= 100 ? x.toFixed(0) : Math.abs(x) >= 10 ? x.toFixed(1) : Math.abs(x) >= 1 ? x.toFixed(2) : x.toPrecision(2))
const rng = (xs) => { xs = xs.filter((x) => x !== null && x !== undefined); if (!xs.length) return '—'; const a = Math.min(...xs), b = Math.max(...xs); return a === b ? f2(a) : f2(a) + ' to ' + f2(b) }
const n = (x) => (typeof x === 'number' ? x.toLocaleString('en-US') : String(x))
const p = (s) => console.log(s)
const WORLDS = ['g4', 'g16', 'elastic', 'stress']
const find = (w, fix, mutate = 'none', ring, floor = mutate === 'mixedfloor' || mutate === 'gonewait' ? 'acked' : 'exact') => sim.find((x) => x.world === w && x.fix === fix && x.mutate === mutate && (x.floor ?? 'exact') === floor && (ring === undefined || x.ring === ring))
const stuck = (r) => r.kinds.stuck ?? 0
const split = (r) => (r ? `${n(r.failed)} (${n(r.failed - stuck(r))} / ${n(stuck(r))})` : '—') // failed (on answers / stuck)
const rowless = (r) => { const all = r.failedNoCase - r.failedNoAnyCase, st = (r.kindsNoRow?.stuck ?? 0) - (r.kindsNoAny?.stuck ?? 0); return all ? `${n(all)} (${n(st)} stuck)` : '0' }
const kinds = (r) => Object.entries(r.kinds).sort((a, b) => b[1] - a[1]).map(([k, v]) => k + ' ' + v).join(', ') || '—'

p('# E-67 results\n')
p('Generated by `bench/summarize.mjs` from `sim.jsonl` and `bench.jsonl`. Every seeded line is 1,000 seeds of 600 steps (300 keys, 1,024 slots). Timed cells: the range over three runs, each run alone under the timing lock; inside a run, the median of 5 rounds (3 for the largest).\n')

p('## 1. The forms, in the four worlds\n')
p('A seed fails at its first wrong answer, a key held twice, a place that goes back, a health line that is wrong (all "on answers"), or a merger that cannot drain at the end ("stuck": it wedged). Rule 4\'s case: a picture that passed a half whose partner it did not hold; "with rows" when the move carried rows. The rebuild floor here is the dead merger\'s own last places (section 5b has the floor from the hosts\' acks).\n')
p('| world | form | seeds failed (on answers / stuck) | seeds with a case: any half / with rows | failed, no case at all | failed, cases without rows only | first failures | joins | checks (full) |')
p('|---|---|---|---|---|---|---|---|---|')
for (const w of WORLDS) for (const fix of ['none', 'a', 'b', 'b0', 'c']) {
  const r = find(w, fix, 'none', fix === 'b' || fix === 'b0' ? 64 : undefined); if (!r) continue
  p(`| ${w} | ${fix} | ${split(r)} | ${n(r.seedsWithAnyCase)} / ${n(r.seedsWithCase)} | ${n(r.failedNoAnyCase)} | ${rowless(r)} | ${kinds(r)} | ${n(r.joins)} | ${n(r.checks)} (${n(r.full)}) |`)
}
for (const [w, ring] of [['elastic', 16], ['elastic', 256], ['stress', 16]]) { const r = find(w, 'b', 'none', ring); if (r) p(`| ${w} | b, ring ${ring} | ${split(r)} | ${n(r.seedsWithAnyCase)} / ${n(r.seedsWithCase)} | ${n(r.failedNoAnyCase)} | ${rowless(r)} | ${kinds(r)} | ${n(r.joins)} | ${n(r.checks)} (${n(r.full)}) |`) }

p('\n## 2. What the worlds threw at the merger (per 1,000 seeds)\n')
p('| world | form | moves started (cancelled / fenced / opened / gave up) | slots moved | grows / shrinks / groups removed | takeovers | outages | rebuilds (during an outage) | pictures | case pictures (takeover / rebuild) | with a fence / an open / a given-up fence / several halves | joins of 2+ pictures |')
p('|---|---|---|---|---|---|---|---|---|---|---|---|')
for (const w of WORLDS) for (const fix of ['none', 'a', 'b', 'c']) {
  const r = find(w, fix, 'none', fix === 'b' ? 64 : undefined); if (!r) continue
  p(`| ${w} | ${fix} | ${n(r.moves)} (${n(r.cancels)} / ${n(r.fences)} / ${n(r.opens)} / ${n(r.giveups)}) | ${n(r.slotsMoved)} | ${r.grows} / ${r.shrinks} / ${r.removed} | ${n(r.takeovers)} | ${n(r.outages)} | ${n(r.rebuilds)} (${n(r.rebuildsDown)}) | ${n(r.pictures)} | ${n(r.cases)} (${n(r.caseTake)} / ${n(r.caseRebuild)}) | ${n(r.caseFence)} / ${n(r.caseOpen)} / ${n(r.caseGiveup)} / ${n(r.caseMulti)} | ${n(r.joinPics2)} |`)
}
const tot = (fix, k) => WORLDS.reduce((s, w) => s + (find(w, fix, 'none', fix === 'b' ? 64 : undefined)?.[k] ?? 0), 0)
p(`\nFix (a), the four worlds together: ${n(tot('a', 'checks'))} checks (${n(tot('a', 'full'))} full), ${n(tot('a', 'joins'))} joins, ${n(tot('a', 'moves'))} moves started, ${n(tot('a', 'takeovers'))} takeovers, ${n(tot('a', 'outages'))} outages, ${n(tot('a', 'rebuilds'))} merger rebuilds (${n(tot('a', 'rebuildsDown'))} during an outage), ${n(tot('a', 'cases'))} case pictures, ${n(tot('a', 'healthChecks'))} health checks.`)
p(`Fix (c), the four worlds together: ${n(tot('c', 'checks'))} checks, ${n(tot('c', 'moves'))} moves, ${n(tot('c', 'takeovers'))} takeovers, ${n(tot('c', 'cases'))} case pictures.`)

p('\n## 3. Waits (group-steps, summed over 1,000 seeds; only while the merger serves)\n')
p('"At a move": a group whose next unit is a half or a picture that cannot be taken yet. "Held": of those, the ones that wait on a down group. "Picture": a group frozen while its new host builds its picture.\n')
p('| world | (a) at a move | (c) at a move | (a) / (c) | (a) held | (c) held | (a) / (c) | (a) picture | (b) at a move | (b) held | (b) picture |')
p('|---|---|---|---|---|---|---|---|---|---|---|')
for (const w of WORLDS) {
  const a = find(w, 'a'), c = find(w, 'c'), b = find(w, 'b', 'none', 64); if (!a || !c) continue
  p(`| ${w} | ${n(a.waitMove)} | ${n(c.waitMove)} | ${f2(a.waitMove / c.waitMove)} | ${n(a.held)} | ${n(c.held)} | ${f2(a.held / c.held)} | ${n(a.picWait)} | ${b ? n(b.waitMove) : '—'} | ${b ? n(b.held) : '—'} | ${b ? n(b.picWait) : '—'} |`)
}

p('\n## 4. The ring: takeovers it covered\n')
p('| world | ring | takeovers covered | missed | share covered |')
p('|---|---|---|---|---|')
for (const w of WORLDS) { const r = find(w, 'b', 'none', 64); if (r) p(`| ${w} | 64 | ${n(r.ringHit)} | ${n(r.ringMiss)} | ${(100 * r.ringHit / (r.ringHit + r.ringMiss)).toFixed(1)} % |`) }
for (const [w, ring] of [['elastic', 16], ['elastic', 256], ['stress', 16]]) { const r = find(w, 'b', 'none', ring); if (r) p(`| ${w} | ${ring} | ${n(r.ringHit)} | ${n(r.ringMiss)} | ${(100 * r.ringHit / (r.ringHit + r.ringMiss)).toFixed(1)} % |`) }
p('\nFirst failures of (b0) by the last picture event before them:\n')
for (const w of WORLDS) { const r = find(w, 'b0', 'none', 64); if (r) p(`- ${w}: ${n(r.failed)} failed; ${Object.entries(r.after).map(([k, v]) => k + ' ' + v).join(', ') || '—'}`) }

p('\n## 5. A new merger: the gap before it serves (steps)\n')
p('| world | form | rebuilds | during an outage | gap, no group down: mean (max) | gap, a group down: mean (max) |')
p('|---|---|---|---|---|---|')
for (const w of WORLDS) for (const fix of ['a', 'c']) {
  const r = find(w, fix); if (!r) continue
  p(`| ${w} | ${fix} | ${n(r.rebuilds)} | ${n(r.rebuildsDown)} | ${r.gapN ? f2(r.gapSum / r.gapN) : '—'} (${r.gapMax}) | ${r.gapDownN ? f2(r.gapDownSum / r.gapDownN) : '—'} (${r.gapDownMax}) |`)
}

p('\n## 5b. The floor at a rebuild, from the hosts\' acks (--floor=acked)\n')
p('Each group\'s copies keep the last whole cut the merger acked to them (here one of its last 64 served cuts, drawn per group). A new merger takes the oldest of the up groups\' cuts and every picture starts from it; in (c) the copies send the parts of the moves not closed at it. "Lowered": rebuild pictures whose floor lay below the dead merger\'s place, and the extra halves they named.\n')
p('| world | form | seeds failed (on answers / stuck) | rebuilds | lowered pictures | extra halves | case pictures | checks |')
p('|---|---|---|---|---|---|---|---|')
for (const w of WORLDS) for (const fix of ['a', 'b', 'c']) {
  const r = find(w, fix, 'none', fix === 'b' ? 64 : undefined, 'acked'); if (!r) continue
  p(`| ${w} | ${fix} | ${split(r)} | ${n(r.rebuilds)} | ${n(r.floorPics)} | ${n(r.floorHalves)} | ${n(r.cases)} | ${n(r.checks)} |`)
}

p('\n## 6. Planted bugs (seeds failed of 1,000)\n')
const PL = [
  ['a', 'nopair', "O1's rule 2: a move's halves taken one by one"],
  ['a', 'resyncadd', "O1's rule 3: a picture added without taking the old part out"],
  ['a', 'back', "O1's rule 1: a picture behind the merger's place is taken"],
  ['a', 'noclosure', "rule 2's closure: a half met on the way to a partner does not bring its own partner"],
  ['a', 'keyowner', "keys kept apart: O1's one entry per key"],
  ['a', 'nojoin', "rule 4's join: a picture's first half joined, the others later"],
  ['a', 'rebuildnol', "rule 4 at a rebuild: a new merger's pictures carry no halves"],
  ['a', 'health', 'health names down groups only, not the groups they hold'],
  ['a', 'giveup', 'a pair whose partner is down: after 30 steps, take the unit alone'],
  ['a', 'giveupskip', 'a pair whose partner is down: after 30 steps, drop the waiting half'],
  ['b', 'ringgap', "the resume rule (ring of 16): resume from the ring's oldest frame though it does not reach back"],
  ['c', 'nomovepart', 'the move part: a fence taken alone with no part for its rows'],
  ['c', 'noorder', 'an open does not wait for its fence'],
  ['c', 'noclosure', 'the closure: a half met on the way does not bring its own fence'],
  ['c', 'nojoin', "the join: a picture's first half joined, the others later"],
  ['c', 'nomoverows', "a picture carries no move part's rows"],
  ['c', 'droprows', "copies drop a fenced move's rows once B has opened, not once the merger closed the move"],
  ['c', 'rebuildnomove', "a new merger gets back only the move parts fenced after its floor"],
  ['c', 'keyowner', "keys kept apart: O1's one entry per key"],
  ['c', 'giveup', 'an open whose fence is at a down group: after 30 steps, take it alone'],
  ['a', 'mixedfloor', "the rebuild floor: each group starts from its own kept cut, not one cut (floor from acks)"],
  ['c', 'mixedfloor', "the rebuild floor: each group starts from its own kept cut, not one cut (floor from acks)"],
]
p('Each cell: seeds failed (on answers / stuck). "No case at all": failing seeds where no picture passed any half.\n')
p('| form | planted | what it breaks | g4 | stress | of those, seeds with no case at all (g4 / stress) | first failures (stress) |')
p('|---|---|---|---|---|---|---|')
for (const [fix, m, what] of PL) {
  const a = find('g4', fix, m), b = find('stress', fix, m)
  p(`| ${fix} | \`${m}\` | ${what} | ${split(a)} | ${split(b)} | ${a ? n(a.failedNoAnyCase) : '—'} / ${b ? n(b.failedNoAnyCase) : '—'} | ${b ? kinds(b) : '—'} |`)
}
p('\nIn elastic, where groups are removed (floor from acks):\n')
p('| form | planted | what it breaks | elastic | first failures |')
p('|---|---|---|---|---|')
for (const fix of ['a', 'c']) { const r = find('elastic', fix, 'gonewait'); if (r) p(`| ${fix} | \`gonewait\` | a removed group is not past the halves it held: a half waits for it, and in (c) a part for a move into it is installed | ${split(r)} | ${kinds(r)} |`) }

if (bench.length) {
  p('\n## 7. Timings\n')
  const B = (part, f) => bench.filter((x) => x.part === part && f(x))
  p('**A picture takeover, at the new host** (fix a): build the partial over the group\'s rows, then take the picture.\n')
  p('| rows | build (ms) | picture (ms) | total (ms) | picture as JSON (bytes) |')
  p('|---|---|---|---|---|')
  for (const nn of [1e4, 1e5, 1e6]) { const r = B('picture', (x) => x.n === nn); if (r.length) p(`| ${n(nn)} | ${rng(r.map((x) => x.buildMs))} | ${rng(r.map((x) => x.pictureMs))} | ${rng(r.map((x) => x.totalMs))} | ${n(r[0].bytes)} |`) }
  p('\n**The merger installs one picture** while it holds G groups of the same size (it takes nothing from any group meanwhile).\n')
  p('| rows a group | G | one entry per key, O1 (ms) | groups kept apart (ms) |')
  p('|---|---|---|---|')
  for (const nn of [1e4, 1e5, 1e6]) for (const G of [1, 4, 16]) {
    const o = B('install', (x) => x.n === nn && x.G === G && x.keys === 'one'), g = B('install', (x) => x.n === nn && x.G === G && x.keys === 'group')
    if (o.length) p(`| ${n(nn)} | ${G} | ${rng(o.map((x) => x.installMs))} | ${rng(g.map((x) => x.installMs))} |`)
  }
  p('\n**The ring** (fix b): the partial on a copy, per record; encoded as JSON for a ring of bytes; and a resend of R frames taken by the merger.\n')
  p('| rows | partial | records | per record (µs) | per record, encoded (µs) | bytes a frame | resend 16 (µs) | resend 64 (µs) | resend 256 (µs) |')
  p('|---|---|---|---|---|---|---|---|---|')
  for (const nn of [1e5, 1e6]) for (const form of ['sums', 'top10', 'six']) {
    const r = B('ring', (x) => x.n === nn && x.form === form); if (!r.length) continue
    const rs = (k) => (form === 'six' ? '—' : rng(r.map((x) => x[k])))
    p(`| ${n(nn)} | ${form} | ${n(r[0].records)} | ${rng(r.map((x) => x.perRecordUs))} | ${rng(r.map((x) => x.perRecordEncodedUs))} | ${f2(r[0].bytesPerFrame)} | ${rs('resend16Us')} | ${rs('resend64Us')} | ${rs('resend256Us')} |`)
  }
  p('\nThe six-view resend is not shown: the bench applies only each frame\'s sums and window parts, so it would read too low. At 1e6 rows the run is shorter (50,000 records against 200,000) and its rows are spread over a larger heap, so its per-record times are noisier.')
  p('\n**A move part** (fix c): the moving slots\' rows become a part at the merger, and later leave.\n')
  p('| rows a resource | slots (of 4,096) | rows | make, install and drop (ms) | rows as JSON (bytes) |')
  p('|---|---|---|---|---|')
  for (const nn of [1e5, 1e6]) for (const sl of [1, 8, 64]) { const r = B('movepart', (x) => x.n === nn && x.slots === sl); if (r.length) p(`| ${n(nn)} | ${sl} | ${n(r[0].rows)} | ${rng(r.map((x) => x.partMs))} | ${n(r[0].rowsBytes)} |`) }
}
