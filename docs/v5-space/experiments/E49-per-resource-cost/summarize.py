# Every process reading is pooled, from every run that took one (added after the re-check: one statistic for both tables).
# boot = RSS about 11 s after the boot ended; a20 / a40 = RSS 20 s / 40 s after the forced collection that follows it;
# heap = live heap after a later forced collection (cluster.mjs: the window's, 20 s on; boot.mjs: the second `mem`'s).
Cl = rows('cluster.jsonl'); B = rows('boot.jsonl'); G = rows('gc.jsonl')
MEM = {}
def mem_add(R, src, boot=(), a20=(), a40=(), heap=()):
    d = MEM.setdefault(R, {'boot': [], 'a20': [], 'a40': [], 'heap': [], 'src': []})
    d['boot'] += boot; d['a20'] += a20; d['a40'] += a40; d['heap'] += heap
    if src not in d['src']:
        d['src'].append(src)
for r in Cl:
    mem_add(r['R'], 'cluster.jsonl', boot=[m['rss_kb'] / 1024 for m in r['mem']], a20=[w['rss_kb'] / 1024 for w in r['window']],
            heap=[w['heap_kb'] / 1024 for w in r['window']])
for r, src in [(r, 'boot.jsonl (' + r['tag'].rsplit('-R', 1)[0] + ')') for r in B] + [(r, 'gc.jsonl') for r in G]:
    if 'mem' not in r or 'mem2' not in r:
        continue
    after = r.get('mem2_after_s', 40 if r.get('slices') else 20)   # gc runs: 4 slices of 10 s; dep13 runs before the field: wait=20
    mem_add(r['R'], src, boot=[m['rss_kb'] / 1024 for m in r['mem']], heap=[m['heap_kb'] / 1024 for m in r['mem2']],
            **{'a40' if after == 40 else 'a20': [m['rss_kb'] / 1024 for m in r['mem2']]})

