#!/usr/bin/env python3
"""E-49: tables from results/parts.jsonl, results/cluster.jsonl and results/disk.jsonl, and from the runs added after
the skeptic's check: results/boot.jsonl, gc.jsonl, dirdrop.jsonl and genesis.jsonl (markdown on stdout).
Usage: python3 summarize.py <results dir>"""
import json, os, statistics as st, sys

RES = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), 'results')


def rows(name):
    p = os.path.join(RES, name)
    if not os.path.exists(p):
        return []
    out = []
    for line in open(p):
        line = line.strip()
        if line.startswith('{'):
            r = json.loads(line)
            if not r.get('marker'):
                out.append(r)
    return out


def med(xs):
    return st.median(xs) if xs else float('nan')


def rng(xs, f='{:.0f}'):
    return f.format(med(xs)) + ' (' + f.format(min(xs)) + '-' + f.format(max(xs)) + ')' if len(xs) > 1 else f.format(xs[0])


def kb(b):
    return f'{b / 1024:.2f}' if abs(b) < 10240 else f'{b / 1024:.1f}'


print('# E-49 tables (generated by summarize.py; do not edit by hand)\n')

