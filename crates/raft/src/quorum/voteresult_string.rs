//! Port of `quorum/voteresult_string.go` (generated by Go's `stringer`).

use super::VoteResult;
use core::fmt;

impl fmt::Display for VoteResult {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        // A Rust enum cannot hold a value outside its three cases, so the
        // `VoteResult(n)` fallback of the Go code has no counterpart.
        f.write_str(match self {
            VoteResult::VotePending => "VotePending",
            VoteResult::VoteLost => "VoteLost",
            VoteResult::VoteWon => "VoteWon",
        })
    }
}
